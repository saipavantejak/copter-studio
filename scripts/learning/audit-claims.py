def add(rows,claim,path,value,status,cmd,note=''):
 rows.append(dict(zip(fields,[str(claim),path,str(value),status,cmd,note])))
def leaves(value,path=''):
 if isinstance(value,dict):
  for k,v in value.items():yield from leaves(v,path+'/'+str(k).replace('~','~0').replace('/','~1'))
 elif isinstance(value,list):
  for i,v in enumerate(value):yield from leaves(v,path+'/'+str(i))
 elif isinstance(value,(int,float)) and not isinstance(value,bool):yield path,value,'numeric'
 elif isinstance(value,str) and re.search(r'\d',value) and not re.search(r'https?://|^[a-f0-9]{32,}$',value):yield path,value,'metadata'
def lookup(value,path):
 for part in path.split('/')[1:]:
  part=part.replace('~1','/').replace('~0','~');value=value[int(part)] if isinstance(value,list) else value[part]
 return value
def match(a,b):
 return math.isclose(a,b,rel_tol=1e-10,abs_tol=1e-12) if isinstance(a,(int,float)) and isinstance(b,(int,float)) else a==b
